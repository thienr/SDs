function present(card: Card): Concept {
  const extra = lesson[card.id];
  return { ...card, ...extra, eyebrow: "C2 · Inferential Statistics" };
}

export const inferConcepts: Concept[] = inferSessions.flatMap((session) => session.concepts.map(present));

export function getConcept(id: string) {
  return inferConcepts.find((concept) => concept.id === id) ?? null;
}

export function conceptNeighbors(id: string) {
  const index = inferConcepts.findIndex((concept) => concept.id === id);
  return {
    prev: index > 0 ? inferConcepts[index - 1] : null,
    next: index >= 0 && index < inferConcepts.length - 1 ? inferConcepts[index + 1] : null,
    index,
    total: inferConcepts.length,
  };
}

export function conceptCopy(concept: Concept, lang: Lang) {
  if (lang !== "en") {
    return {
      title: concept.title,
      why: concept.why,
      prior: concept.prior,
      see: concept.see,
      plain: concept.plain,
      situation: concept.situation,
      use: concept.use,
      precise: concept.precise,
      insight: concept.insight,
      formula: concept.formula,
      symbols: concept.symbols,
    };
  }
  const en = enConcept[concept.id];
  if (!en) {
    return conceptCopy(concept, "vi");
  }
  return {
    title: en.title,
    why: en.why,
    prior: en.prior,
    see: en.see,
    plain: en.plain,
    situation: en.situation,
    use: en.use,
    precise: en.precise,
    insight: en.insight,
    formula: en.formula ?? concept.formula,
    symbols: concept.symbols.map((row, index) => ({ sym: row.sym, meaning: en.symbols[index] ?? row.meaning })),
  };
}

