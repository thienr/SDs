export type C4Concept = Card & { eyebrow: string };

export const c4Concepts: C4Concept[] = c4Sessions.flatMap((session) =>
  session.concepts.map((concept) => ({ ...concept, eyebrow: "C4 · Advanced ML" })),
);

export function getC4Concept(id: string) {
  return c4Concepts.find((concept) => concept.id === id) ?? null;
}

export function c4Neighbors(id: string) {
  const index = c4Concepts.findIndex((concept) => concept.id === id);
  return {
    prev: index > 0 ? c4Concepts[index - 1] : null,
    next: index >= 0 && index < c4Concepts.length - 1 ? c4Concepts[index + 1] : null,
    index,
    total: c4Concepts.length,
  };
}

export function c4Copy(concept: C4Concept, lang: Lang) {
  if (lang !== "en") {
    return {
      title: concept.title,
      why: concept.why,
      prior: concept.prior,
      see: concept.see,
      plain: concept.plain,
      situation: concept.situation,
      use: concept.use,
      precise: concept.precise,
      insight: concept.insight,
      formula: concept.formula,
      symbols: concept.symbols,
    };
  }
  const en = c4En[concept.id];
  if (!en) return c4Copy(concept, "vi");
  return {
    title: en.title,
    why: en.why,
    prior: en.prior,
    see: en.see,
    plain: en.plain,
    situation: en.situation,
    use: en.use,
    precise: en.precise,
    insight: en.insight,
    formula: concept.formula,
    symbols: concept.symbols.map((row, index) => ({ sym: row.sym, meaning: en.symbols[index] ?? row.meaning })),
  };
}
