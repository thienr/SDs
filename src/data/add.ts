function brow(courseId: string) {
  return courseId === MATH ? "Toán" : "Mô tả";
}

export type AddConcept = Card & { eyebrow: string; courseId: string };

export const addConcepts: AddConcept[] = addSessions.flatMap((session) =>
  session.concepts.map((concept) => ({ ...concept, eyebrow: brow(session.courseId), courseId: session.courseId })),
);

export function getAddConcept(id: string) {
  return addConcepts.find((concept) => concept.id === id) ?? null;
}

export function addNeighbors(id: string) {
  const current = addConcepts.find((concept) => concept.id === id);
  const chain = current ? addConcepts.filter((concept) => concept.courseId === current.courseId) : [];
  const index = chain.findIndex((concept) => concept.id === id);
  return {
    prev: index > 0 ? chain[index - 1] : null,
    next: index >= 0 && index < chain.length - 1 ? chain[index + 1] : null,
    index,
    total: chain.length,
  };
}

export function addCopy(concept: AddConcept, lang: Lang) {
  if (lang !== "en") {
    return {
      title: concept.title,
      why: concept.why,
      prior: concept.prior,
      see: concept.see,
      plain: concept.plain,
      situation: concept.situation,
      use: concept.use,
      precise: concept.precise,
      insight: concept.insight,
      formula: concept.formula,
      symbols: concept.symbols,
    };
  }
  const en = addEn[concept.id];
  if (!en) return addCopy(concept, "vi");
  return {
    title: en.title,
    why: en.why,
    prior: en.prior,
    see: en.see,
    plain: en.plain,
    situation: en.situation,
    use: en.use,
    precise: en.precise,
    insight: en.insight,
    formula: concept.formula,
    symbols: concept.symbols.map((row, index) => ({ sym: row.sym, meaning: en.symbols[index] ?? row.meaning })),
  };
}
