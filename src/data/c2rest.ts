function brow(module: string) {
  if (module === "Hypothesis Testing") return "C2 · Hypothesis Testing";
  if (module === "Exploratory Data Analysis") return "C2 · EDA";
  return "C2 · SQL";
}

export type RestConcept = Card & { eyebrow: string };

export const restConcepts: RestConcept[] = restSessions.flatMap((session) =>
  session.concepts.map((concept) => ({ ...concept, eyebrow: brow(concept.module) })),
);

export function getRestConcept(id: string) {
  return restConcepts.find((concept) => concept.id === id) ?? null;
}

export function restNeighbors(id: string) {
  const index = restConcepts.findIndex((concept) => concept.id === id);
  return {
    prev: index > 0 ? restConcepts[index - 1] : null,
    next: index >= 0 && index < restConcepts.length - 1 ? restConcepts[index + 1] : null,
    index,
    total: restConcepts.length,
  };
}

export function restCopy(concept: RestConcept, lang: Lang) {
  if (lang !== "en") {
    return {
      title: concept.title,
      why: concept.why,
      prior: concept.prior,
      see: concept.see,
      plain: concept.plain,
      situation: concept.situation,
      use: concept.use,
      precise: concept.precise,
      insight: concept.insight,
      formula: concept.formula,
      symbols: concept.symbols,
    };
  }
  const en = restEn[concept.id];
  if (!en) return restCopy(concept, "vi");
  return {
    title: en.title,
    why: en.why,
    prior: en.prior,
    see: en.see,
    plain: en.plain,
    situation: en.situation,
    use: en.use,
    precise: en.precise,
    insight: en.insight,
    formula: concept.formula,
    symbols: concept.symbols.map((row, index) => ({ sym: row.sym, meaning: en.symbols[index] ?? row.meaning })),
  };
}
