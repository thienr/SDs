export type MlConcept = Card & { eyebrow: string };

export const mlConcepts: MlConcept[] = mlSessions.flatMap((session) =>
  session.concepts.map((concept) => ({ ...concept, eyebrow: "C3 · Machine Learning" })),
);

export function getMlConcept(id: string) {
  return mlConcepts.find((concept) => concept.id === id) ?? null;
}

export function mlNeighbors(id: string) {
  const index = mlConcepts.findIndex((concept) => concept.id === id);
  return {
    prev: index > 0 ? mlConcepts[index - 1] : null,
    next: index >= 0 && index < mlConcepts.length - 1 ? mlConcepts[index + 1] : null,
    index,
    total: mlConcepts.length,
  };
}

export function mlCopy(concept: MlConcept, lang: Lang) {
  if (lang !== "en") {
    return {
      title: concept.title,
      why: concept.why,
      prior: concept.prior,
      see: concept.see,
      plain: concept.plain,
      situation: concept.situation,
      use: concept.use,
      precise: concept.precise,
      insight: concept.insight,
      formula: concept.formula,
      symbols: concept.symbols,
    };
  }
  const en = mlEn[concept.id];
  if (!en) return mlCopy(concept, "vi");
  return {
    title: en.title,
    why: en.why,
    prior: en.prior,
    see: en.see,
    plain: en.plain,
    situation: en.situation,
    use: en.use,
    precise: en.precise,
    insight: en.insight,
    formula: concept.formula,
    symbols: concept.symbols.map((row, index) => ({ sym: row.sym, meaning: en.symbols[index] ?? row.meaning })),
  };
}
