function brow(module: string) {
  return module === "Intro to GIT and GITHUB" ? "C3 · Git" : "C3 · Machine Learning";
}

export type MoreConcept = Card & { eyebrow: string };

export const moreConcepts: MoreConcept[] = moreSessions.flatMap((session) =>
  session.concepts.map((concept) => ({ ...concept, eyebrow: brow(concept.module) })),
);

export function getMoreConcept(id: string) {
  return moreConcepts.find((concept) => concept.id === id) ?? null;
}

export function moreCopy(concept: MoreConcept, lang: Lang) {
  if (lang !== "en") {
    return {
      title: concept.title,
      why: concept.why,
      prior: concept.prior,
      see: concept.see,
      plain: concept.plain,
      situation: concept.situation,
      use: concept.use,
      precise: concept.precise,
      insight: concept.insight,
      formula: concept.formula,
      symbols: concept.symbols,
    };
  }
  const en = moreEn[concept.id];
  if (!en) return moreCopy(concept, "vi");
  return {
    title: en.title,
    why: en.why,
    prior: en.prior,
    see: en.see,
    plain: en.plain,
    situation: en.situation,
    use: en.use,
    precise: en.precise,
    insight: en.insight,
    formula: concept.formula,
    symbols: concept.symbols.map((row, index) => ({ sym: row.sym, meaning: en.symbols[index] ?? row.meaning })),
  };
}
